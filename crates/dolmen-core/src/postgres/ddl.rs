//! `CREATE` statements for schema objects, written the way pg_dump writes them.
//!
//! These describe an object as it is; they are for reading, snapshots and
//! diffs, not a migration script that can be replayed in any order.

use serde::Deserialize;

use crate::schema::{
    Column, Constraint, EnumType, Extension, Function, Identity, Sequence, Table, TableKind, View,
};

/// Any schema object, tagged by `type` so the app can ask for one object's DDL.
#[derive(Debug, Deserialize)]
#[serde(tag = "type", rename_all = "camelCase")]
pub enum SchemaObject {
    Table(Table),
    View(View),
    Function(Function),
    Sequence(Sequence),
    Enum(EnumType),
}

/// The `CREATE` statement of `object` in `schema`.
pub fn create_statement(schema: &str, object: &SchemaObject) -> String {
    match object {
        SchemaObject::Table(table) => create_table(schema, table),
        SchemaObject::View(view) => create_view(schema, view),
        SchemaObject::Function(function) => create_function(function),
        SchemaObject::Sequence(sequence) => create_sequence(schema, sequence),
        SchemaObject::Enum(enum_type) => create_enum(schema, enum_type),
    }
}

pub fn create_schema(name: &str) -> String {
    format!("CREATE SCHEMA {};\n", quote_ident(name))
}

pub fn create_extension(extension: &Extension) -> String {
    format!(
        "CREATE EXTENSION IF NOT EXISTS {} WITH SCHEMA {};\n",
        quote_ident(&extension.name),
        quote_ident(&extension.schema)
    )
}

/// The table with its columns and constraints, then its indexes and comments.
pub fn create_table(schema: &str, table: &Table) -> String {
    let name = qualified(schema, &table.name);
    let mut ddl = table_statement(schema, table, table.constraints.iter());
    for index in &table.indexes {
        ddl.push_str(&format!("\n{};\n", index.definition));
    }
    push_comments(
        &mut ddl,
        table_object(table),
        &name,
        table.comment.as_deref(),
        &table.columns,
    );
    ddl
}

/// Just the `CREATE TABLE` statement, with the given constraints.
pub(crate) fn table_statement<'a>(
    schema: &str,
    table: &Table,
    constraints: impl Iterator<Item = &'a Constraint>,
) -> String {
    let elements: Vec<String> = table
        .columns
        .iter()
        .map(|column| column_definition(schema, &table.name, column))
        .chain(constraints.map(|constraint| {
            format!(
                "CONSTRAINT {} {}",
                quote_ident(&constraint.name),
                constraint.definition
            )
        }))
        .collect();

    let mut ddl = format!(
        "CREATE {} {} (\n",
        table_object(table),
        qualified(schema, &table.name)
    );
    ddl.push_str(
        &elements
            .iter()
            .map(|e| format!("    {e}"))
            .collect::<Vec<_>>()
            .join(",\n"),
    );
    ddl.push_str("\n)");
    if let Some(key) = &table.partition_key {
        ddl.push_str(&format!(" PARTITION BY {key}"));
    }
    ddl.push_str(";\n");
    ddl
}

/// A column as written in `CREATE TABLE` or `ADD COLUMN`.
pub(crate) fn column_definition(schema: &str, table: &str, column: &Column) -> String {
    let serial = serial_type(schema, table, column);
    let data_type = serial.unwrap_or(&column.data_type);
    let mut definition = format!("{} {data_type}", quote_ident(&column.name));
    if let Some(generated) = &column.generated {
        let storage = if generated.stored {
            "STORED"
        } else {
            "VIRTUAL"
        };
        definition.push_str(&format!(
            " GENERATED ALWAYS AS ({}) {storage}",
            generated.expression
        ));
    }
    match column.identity {
        Some(Identity::Always) => definition.push_str(" GENERATED ALWAYS AS IDENTITY"),
        Some(Identity::ByDefault) => definition.push_str(" GENERATED BY DEFAULT AS IDENTITY"),
        None => {}
    }
    if let (Some(default), None) = (&column.default, serial) {
        definition.push_str(&format!(" DEFAULT {default}"));
    }
    if !column.nullable {
        definition.push_str(" NOT NULL");
    }
    definition
}

/// `TABLE` or `FOREIGN TABLE`, as in `CREATE …` and `COMMENT ON …`.
pub(crate) fn table_object(table: &Table) -> &'static str {
    match table.kind {
        TableKind::Foreign => "FOREIGN TABLE",
        TableKind::Table | TableKind::Partitioned => "TABLE",
    }
}

/// `serial`, `bigserial` or `smallserial` for an integer column that defaults to
/// the next value of the sequence PostgreSQL made for it. That sequence belongs
/// to the column and isn't listed on its own, so writing `serial` keeps the
/// table's DDL complete.
fn serial_type(schema: &str, table: &str, column: &Column) -> Option<&'static str> {
    let sequence = qualified(schema, &format!("{table}_{}_seq", column.name));
    let next_value = format!("nextval('{}'::regclass)", sequence.replace('\'', "''"));
    if column.default.as_deref() != Some(next_value.as_str()) || column.identity.is_some() {
        return None;
    }
    match column.data_type.as_str() {
        "integer" => Some("serial"),
        "bigint" => Some("bigserial"),
        "smallint" => Some("smallserial"),
        _ => None,
    }
}

pub fn create_view(schema: &str, view: &View) -> String {
    let name = qualified(schema, &view.name);
    let object = if view.materialized {
        "MATERIALIZED VIEW"
    } else {
        "VIEW"
    };
    // pg_get_viewdef starts the query with a space and ends it with a semicolon.
    let query = view.definition.trim_end().trim_end_matches(';');
    let mut ddl = format!("CREATE {object} {name} AS\n{query};\n");
    push_comments(
        &mut ddl,
        object,
        &name,
        view.comment.as_deref(),
        &view.columns,
    );
    ddl
}

/// pg_get_functiondef's statement, which names the schema itself.
pub fn create_function(function: &Function) -> String {
    format!("{};\n", function.definition.trim_end())
}

pub fn create_sequence(schema: &str, sequence: &Sequence) -> String {
    format!("CREATE SEQUENCE {};\n", qualified(schema, &sequence.name))
}

pub fn create_enum(schema: &str, enum_type: &EnumType) -> String {
    let labels: Vec<String> = enum_type
        .labels
        .iter()
        .map(|l| format!("    {}", quote_literal(l)))
        .collect();
    format!(
        "CREATE TYPE {} AS ENUM (\n{}\n);\n",
        qualified(schema, &enum_type.name),
        labels.join(",\n")
    )
}

fn push_comments(
    ddl: &mut String,
    object: &str,
    name: &str,
    comment: Option<&str>,
    columns: &[Column],
) {
    let mut comments: Vec<String> = comment
        .map(|comment| comment_on(object, name, Some(comment)))
        .into_iter()
        .collect();
    for column in columns {
        if let Some(comment) = &column.comment {
            comments.push(comment_on(
                "COLUMN",
                &format!("{name}.{}", quote_ident(&column.name)),
                Some(comment),
            ));
        }
    }
    if !comments.is_empty() {
        ddl.push('\n');
        ddl.push_str(&comments.join("\n"));
        ddl.push('\n');
    }
}

/// `COMMENT ON <object> <name> IS …`, or `IS NULL` to remove the comment.
pub(crate) fn comment_on(object: &str, name: &str, comment: Option<&str>) -> String {
    let value = comment.map_or_else(|| "NULL".to_owned(), quote_literal);
    format!("COMMENT ON {object} {name} IS {value};")
}

/// `schema.name`, each part quoted as needed.
pub fn qualified(schema: &str, name: &str) -> String {
    format!("{}.{}", quote_ident(schema), quote_ident(name))
}

/// Quotes an identifier unless it is a plain lower-case name that isn't a
/// keyword PostgreSQL restricts, as PostgreSQL's own `quote_ident` does.
pub fn quote_ident(name: &str) -> String {
    let plain = name.starts_with(|c: char| c.is_ascii_lowercase() || c == '_')
        && name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_' || c == '$')
        && !RESERVED.contains(&name);
    if plain {
        name.to_owned()
    } else {
        format!("\"{}\"", name.replace('"', "\"\""))
    }
}

pub(crate) fn quote_literal(text: &str) -> String {
    format!("'{}'", text.replace('\'', "''"))
}

