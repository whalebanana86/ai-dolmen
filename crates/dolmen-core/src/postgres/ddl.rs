#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::{ConstraintKind, Generated, Index};

    fn column(name: &str, data_type: &str) -> Column {
        Column {
            name: name.into(),
            data_type: data_type.into(),
            nullable: true,
            default: None,
            identity: None,
            generated: None,
            comment: None,
        }
    }

    #[test]
    fn quotes_only_when_needed() {
        assert_eq!(quote_ident("users"), "users");
        assert_eq!(quote_ident("_tmp$1"), "_tmp$1");
        assert_eq!(quote_ident("order"), "\"order\"");
        assert_eq!(quote_ident("Users"), "\"Users\"");
        assert_eq!(quote_ident("1st"), "\"1st\"");
        assert_eq!(quote_ident("사람"), "\"사람\"");
        assert_eq!(quote_ident("say \"hi\""), "\"say \"\"hi\"\"\"");
        // Keywords that aren't unreserved, like PostgreSQL's quote_ident.
        for keyword in ["left", "join", "position", "time", "values", "verbose"] {
            assert_eq!(quote_ident(keyword), format!("\"{keyword}\""));
        }
        // Unreserved ones stay plain.
        for word in ["name", "type", "data", "key", "status"] {
            assert_eq!(quote_ident(word), word);
        }
    }

    #[test]
    fn writes_a_table_like_pg_dump() {
        let table = Table {
            name: "order".into(),
            kind: TableKind::Table,
            columns: vec![
                Column {
                    nullable: false,
                    identity: Some(Identity::Always),
                    ..column("id", "bigint")
                },
                Column {
                    nullable: false,
                    default: Some("'new'::text".into()),
                    comment: Some("customer's state".into()),
                    ..column("status", "text")
                },
                Column {
                    generated: Some(Generated {
                        expression: "length(status)".into(),
                        stored: true,
                    }),
                    ..column("status_length", "integer")
                },
            ],
            constraints: vec![Constraint {
                name: "order_pkey".into(),
                kind: ConstraintKind::PrimaryKey,
                definition: "PRIMARY KEY (id)".into(),
            }],
            indexes: vec![Index {
                name: "order_status_idx".into(),
                definition:
                    "CREATE INDEX order_status_idx ON public.\"order\" USING btree (status)".into(),
            }],
            partition_key: None,
            comment: Some("orders".into()),
        };

        assert_eq!(
            create_table("public", &table),
            "CREATE TABLE public.\"order\" (
    id bigint GENERATED ALWAYS AS IDENTITY NOT NULL,
    status text DEFAULT 'new'::text NOT NULL,
    status_length integer GENERATED ALWAYS AS (length(status)) STORED,
    CONSTRAINT order_pkey PRIMARY KEY (id)
);

CREATE INDEX order_status_idx ON public.\"order\" USING btree (status);

COMMENT ON TABLE public.\"order\" IS 'orders';
COMMENT ON COLUMN public.\"order\".status IS 'customer''s state';
"
        );
    }

    #[test]
    fn writes_serial_columns_as_serial() {
        let table = Table {
            name: "posts".into(),
            kind: TableKind::Table,
            columns: vec![
                Column {
                    nullable: false,
                    default: Some("nextval('app.posts_id_seq'::regclass)".into()),
                    ..column("id", "integer")
                },
                // A default from some other sequence stays as written.
                Column {
                    default: Some("nextval('app.shared_seq'::regclass)".into()),
                    ..column("n", "bigint")
                },
            ],
            constraints: vec![],
            indexes: vec![],
            partition_key: None,
            comment: None,
        };
        assert_eq!(
            create_table("app", &table),
            "CREATE TABLE app.posts (\n    id serial NOT NULL,\n    n bigint DEFAULT nextval('app.shared_seq'::regclass)\n);\n"
        );
    }

    #[test]
    fn writes_partition_keys() {
        let table = Table {
            name: "events".into(),
            kind: TableKind::Partitioned,
            columns: vec![column("at", "timestamp with time zone")],
            constraints: vec![],
            indexes: vec![],
            partition_key: Some("RANGE (at)".into()),
            comment: None,
        };
        assert_eq!(
            create_table("app", &table),
            "CREATE TABLE app.events (\n    at timestamp with time zone\n) PARTITION BY RANGE (at);\n"
        );
    }

    #[test]
    fn writes_views_enums_and_sequences() {
        let view = View {
            name: "recent".into(),
            materialized: true,
            columns: vec![column("id", "integer")],
            definition: " SELECT id\n   FROM posts;".into(),
            comment: None,
        };
        assert_eq!(
            create_view("public", &view),
            "CREATE MATERIALIZED VIEW public.recent AS\n SELECT id\n   FROM posts;\n"
        );

        let mood = EnumType {
            name: "mood".into(),
            labels: vec!["sad".into(), "it's ok".into()],
        };
        assert_eq!(
            create_enum("public", &mood),
            "CREATE TYPE public.mood AS ENUM (\n    'sad',\n    'it''s ok'\n);\n"
        );
        assert_eq!(
            create_sequence(
                "billing",
                &Sequence {
                    name: "Invoice".into()
                }
            ),
            "CREATE SEQUENCE billing.\"Invoice\";\n"
        );
    }
}
